#!/usr/bin/env python3
"""gen_eng_client — the C API's functions by name, generated from its headers.

Writes two files from every `ENG_API` declaration in include/eng/*.h:

  include/eng/eng_client.h   what a module that is a shared library compiles
                             against: one forwarding stub per function, filled
                             from the get_proc the engine hands it, so the
                             module links nothing of the engine's (WO-094).
  src/capi/eng_procs.inc     the engine's side: ENG_PROC(name) for each, which
                             engGetProc turns into its table.

Generated, not written by hand, so a function added to a header cannot be
missing from either. `--check` fails, naming the file, when either is not what
the headers give (ctest: eng_client_current).

    python3 scripts/gen_eng_client.py          # write both
    python3 scripts/gen_eng_client.py --check  # exit 1 if either is stale
"""
from __future__ import annotations

import argparse
import re
import sys
from pathlib import Path

REPO = Path(__file__).resolve().parent.parent
HEADERS = REPO / "include" / "eng"
CLIENT = HEADERS / "eng_client.h"
PROCS = REPO / "src" / "capi" / "eng_procs.inc"

_COMMENT = re.compile(r"/\*.*?\*/|//[^\n]*", re.S)
_DECL = re.compile(r"\bENG_API\s+([^;{}]*?)\b(eng[A-Za-z0-9_]+)\s*\(([^;{}]*?)\)\s*;", re.S)


def declarations() -> list[tuple[str, str, str]]:
    """(return type, name, parameters) in header order, then file order."""
    out = []
    for h in sorted(HEADERS.glob("*.h")):
        if h.name == CLIENT.name:
            continue
        text = _COMMENT.sub(" ", h.read_text(encoding="utf-8"))
        text = re.sub(r"#\s*define[^\n]*", " ", text)   # the ENG_API macros themselves
        for m in _DECL.finditer(text):
            ret = " ".join(m.group(1).split())
            params = " ".join(m.group(3).split())
            out.append((ret, m.group(2), params))
    names = [n for _, n, _ in out]
    dup = {n for n in names if names.count(n) > 1}
    if dup:
        sys.exit(f"gen_eng_client: declared twice: {', '.join(sorted(dup))}")
    return out


def arg_names(params: str) -> str:
    if params in ("", "void"):
        return ""
    names = []
    for p in params.split(","):
        p = re.sub(r"\[[^\]]*\]", "", p).strip()
        m = re.search(r"([A-Za-z_][A-Za-z0-9_]*)\s*$", p)
        if not m:
            sys.exit(f"gen_eng_client: a parameter has no name: '{p}' (name every parameter)")
        names.append(m.group(1))
    return ", ".join(names)


HEAD = """/* GENERATED by scripts/gen_eng_client.py from the headers in include/eng: do not edit.
 *
 * eng_client.h: the engine's C API for a module that is a shared library
 * (eng_module.h). Build the whole module with ENG_CLIENT defined, and in one
 * source file:
 *
 *   #define ENG_CLIENT_IMPLEMENTATION
 *   #include <eng/eng_client.h>
 *
 *   ENG_MODULE_EXPORT const EngModuleDesc* engModuleEntry(EngGetProcFn get_proc) {
 *       if (engClientLoad(get_proc, NULL) != ENG_OK) return NULL;
 *       return myKit();
 *   }
 *
 * Every eng* function is then the module's own stub, forwarding to the
 * function the engine named. Nothing of the engine's is linked or resolved
 * from the host, so the module loads into any host of this API version. */
#ifndef ENG_CLIENT_H
#define ENG_CLIENT_H
#ifndef ENG_CLIENT
#  error "define ENG_CLIENT for the whole module: it makes the eng* functions its own stubs"
#endif
#include "engine.h"

ENG_EXTERN_C_BEGIN

/* Fills every stub from get_proc. ENG_ERROR_NOT_FOUND if the engine lacks one,
 * with its name in *missing_or_null; a stub left unfilled must not be called. */
ENG_API EngResult engClientLoad(EngGetProcFn get_proc, const char** missing_or_null);

#ifdef ENG_CLIENT_IMPLEMENTATION
"""

TAIL = """#endif /* ENG_CLIENT_IMPLEMENTATION */

ENG_EXTERN_C_END
#endif /* ENG_CLIENT_H */
"""


def client(decls) -> str:
    lines = [HEAD]
    for ret, name, params in decls:
        lines.append(f"typedef {ret} (*EngClientFn_{name})({params});\n")
    lines.append("\nstatic struct {\n")
    for _, name, _ in decls:
        lines.append(f"    EngClientFn_{name} {name};\n")
    lines.append("} eng_client_procs;\n\n")
    for ret, name, params in decls:
        call = f"eng_client_procs.{name}({arg_names(params)})"
        body = f"{call};" if ret == "void" else f"return {call};"
        lines.append(f"ENG_API {ret} {name}({params}) {{ {body} }}\n")
    lines.append("\nENG_API EngResult engClientLoad(EngGetProcFn get_proc, const char** missing_or_null) {\n")
    lines.append("    if (missing_or_null) *missing_or_null = NULL;\n")
    lines.append("    if (!get_proc) return ENG_ERROR_INVALID_ARGUMENT;\n")
    lines.append("#define ENG_CLIENT_LOAD(n) \\\n")
    lines.append("    if (!(eng_client_procs.n = (EngClientFn_##n)get_proc(#n))) { \\\n")
    lines.append("        if (missing_or_null) *missing_or_null = #n; \\\n")
    lines.append("        return ENG_ERROR_NOT_FOUND; \\\n")
    lines.append("    }\n")
    for _, name, _ in decls:
        lines.append(f"    ENG_CLIENT_LOAD({name})\n")
    lines.append("#undef ENG_CLIENT_LOAD\n    return ENG_OK;\n}\n")
    lines.append(TAIL)
    return "".join(lines)


def procs(decls) -> str:
    head = ("// GENERATED by scripts/gen_eng_client.py from include/eng/*.h: do not edit.\n"
            "// Every C API function, for engGetProc's table (src/capi/eng_capi.cpp).\n")
    return head + "".join(f"ENG_PROC({name})\n" for _, name, _ in decls)


def main() -> int:
    ap = argparse.ArgumentParser(description=__doc__.split("\n\n")[0])
    ap.add_argument("--check", action="store_true", help="exit 1 if a generated file is stale")
    args = ap.parse_args()
    decls = declarations()
    want = {CLIENT: client(decls), PROCS: procs(decls)}
    stale = [p for p, text in want.items() if not p.exists() or p.read_text(encoding="utf-8") != text]
    if args.check:
        for p in stale:
            print(f"gen_eng_client: {p.relative_to(REPO)} is stale: run python3 scripts/gen_eng_client.py")
        if not stale:
            print(f"gen_eng_client: {len(decls)} functions, both files current")
        return 1 if stale else 0
    for p, text in want.items():
        p.write_text(text, encoding="utf-8", newline="\n")
    print(f"gen_eng_client: {len(decls)} functions written")
    return 0


if __name__ == "__main__":
    sys.exit(main())
